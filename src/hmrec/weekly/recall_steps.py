"""The recall steps of a tick: O1 (the six channels) and C4 (the R6 fine-tune). Torch side.

Nothing is computed here that stage 1 did not compute. The channels are built
only from the lock files (hmrec.recall.locked) and generated by the stage-1
functions (hmrec.recall.generate); they get the tick's paths
(hmrec.paths.PipelinePaths), so they read the tick's ingested transactions and
write into the tick's week folder.

What differs from stage 1 is WHEN the R6 chain is advanced. In stage 1 one
process predicted a week and then fine-tuned on it (the week's purchases were in
the data). In a weekly pipeline the purchases of a week exist only after it:

    tick at anchor a    C4  fine-tune on the week before a, starting from the
                            model that predicted that week; save the new model
                            and its record (sha256, losses)
                        O1  predict the week of a with that new model

The computation is the same function, hmrec.recall.generate.fine_tune_twotower_fold,
with the same seeds (they depend on the week's anchor, not on the process).

The chain rule of stage 1 holds: a model is used only if its file has the sha256
of its record, and a week can be fine-tuned only from the model of the week
before it (chain_model_of). So no week can be skipped.

`serve` mode writes the candidates shard by shard (hmrec.weekly.shard_recall).

No label is read here. C4 reads the purchases of the closed week, which lie
before the tick's anchor.
"""

from dataclasses import dataclass

import polars as pl
import torch

from hmrec.config import load_candidate_run_config, load_catalog_config
from hmrec.locks import ALL_CHANNELS, R6_CHANNEL, check_file_sha256
from hmrec.logging_utils import get_logger
from hmrec.recall.base import RecallInputs
from hmrec.recall.chain_records import ChainRecord, read_chain_records
from hmrec.recall.generate import (
    R1_CHANNEL,
    R5_CHANNEL,
    FoldJob,
    check_fine_tune_loss,
    fine_tune_twotower_fold,
    generate_statistical_channel,
    predict_twotower_fold,
)
from hmrec.recall.inputs import SharedTables, build_recall_inputs, load_shared_tables
from hmrec.recall.locked import (
    LockedRecall,
    ModelFile,
    load_locked_recall,
    load_locked_twotower_chain,
)
from hmrec.recall.twotower.chain import TwoTowerChainChannel
from hmrec.run_manifest import EVAL_MODE, MetricRecord
from hmrec.vectors import METADATA_FILE
from hmrec.weekly.calendar import Week, previous_week
from hmrec.weekly.context import OutputFile, TickContext
from hmrec.weekly.shard_recall import RecallJob, generate_channel
from hmrec.weekly.steps import Step

LOGGER = get_logger("weekly.recall_steps")

BOOTSTRAP_CHAIN_TABLE = "m6_twotower_chain.csv"
CANDIDATES_FILE = "candidates.parquet"

StepOutcome = tuple[str, list[MetricRecord], list[OutputFile]]


@dataclass(frozen=True)
class RecallSetup:
    """What a recall process reads once.

    Attributes:
        locked: Both recall lock files.
        tables: The processed tables; the transactions are the tick's ingested ones.
    """

    locked: LockedRecall
    tables: SharedTables


def load_recall_setup(context: TickContext) -> RecallSetup:
    """Read the lock files and the tables, and set torch's thread count."""
    torch.set_num_threads(context.base.num_threads)
    return RecallSetup(
        locked=load_locked_recall(context.view),
        tables=load_shared_tables(context.view, context.preprocess),
    )


def week_inputs(context: TickContext, setup: RecallSetup, week: Week) -> RecallInputs:
    """The channel inputs as of a week's anchor, with its active pool A(a)."""
    catalog = load_catalog_config(context.paths.catalog_config_file)
    return build_recall_inputs(setup.tables, week.fold, context.preprocess, catalog)


# ---------------------------------------------------------------- the R6 chain


def chain_record_of(context: TickContext, week: Week) -> ChainRecord:
    """The record of the chain model that was fine-tuned on `week`.

    A week before the first tick: the row of the bootstrap state's chain table.
    A week of the pipeline: the record step C4 wrote next to the model.

    Raises:
        ValueError: If the week has no record: it was not fine-tuned yet, so the
            chain has not reached the next week.
    """
    if week.ordinal < context.first_week.ordinal:
        table = context.paths.bootstrap_monitoring_file(BOOTSTRAP_CHAIN_TABLE)
    else:
        table = context.view.chain_record_file(week.name)
    records = read_chain_records(table)
    if week.name not in records:
        raise ValueError(
            f"week {week.name} has no chain record in {table}: the R6 chain was not "
            "fine-tuned on it yet. The chain may not skip a week."
        )
    return records[week.name]


def chain_model_of(context: TickContext, week: Week) -> ModelFile:
    """The chain model after the fine-tune on `week`, checked against its record.

    This is the model that predicts the week AFTER `week`, and the start of the
    next fine-tune.

    Raises:
        FileNotFoundError: If the model file is missing.
        ValueError: If the week has no record or the file has another sha256.
    """
    record = chain_record_of(context, week)
    path = context.view.twotower_locked_chain_checkpoint_file(week.name)
    check_file_sha256(path, record.sha256)
    return ModelFile(path, record.sha256)


def load_chain(context: TickContext, setup: RecallSetup, start: ModelFile) -> TwoTowerChainChannel:
    """The locked R6 chain with `start` loaded (sha256 checked again by the loader)."""
    return load_locked_twotower_chain(
        setup.locked, context.base, context.view, context.preprocess, start
    )


def run_fine_tune(context: TickContext) -> StepOutcome:
    """C4: advance the R6 chain by one week, on the week the tick closes.

    Starts from the model that predicted the closed week (the model after the
    week before it), fine-tunes on the closed week's purchases with the locked
    settings, saves the model and writes its record. Then checks the losses
    against the stop limit of configs/m6_candidates.yaml.

    Raises:
        ValueError: If the start model is missing its record or has another
            sha256, or a loss is not finite or above the limit.
    """
    closing = context.closing
    setup = load_recall_setup(context)
    start = chain_model_of(context, previous_week(closing, context.manifest))
    chain = load_chain(context, setup, start)
    LOGGER.info("C4: fine-tuning on %s (%s) from %s", closing.name, closing.anchor, start.path)
    record = fine_tune_twotower_fold(
        chain,
        closing.fold,
        week_inputs(context, setup, closing),
        start,
        context.stamp,
        context.view.chain_record_file(closing.name),
    )
    max_loss = load_candidate_run_config(context.paths.m6_config_file).max_fine_tune_loss
    check_fine_tune_loss(record, max_loss)
    runtime = chain.fine_tune_runtime_settings[closing.name]
    detail = (
        f"fine-tuned on {closing.name}: {record.n_new_rows} new + {record.n_replay_rows} replay "
        f"rows, train loss {record.mean_train_loss:.4f}, alarm loss {record.alarm_loss:.4f}, "
        f"{record.fine_tune_seconds:.1f} s, runtime setting {runtime}, sha256 {record.sha256}"
    )
    metrics = [
        MetricRecord("r6_chain/train_loss", closing.anchor, record.mean_train_loss),
        MetricRecord("r6_chain/alarm_loss", closing.anchor, record.alarm_loss),
        MetricRecord("r6_chain/fine_tune_seconds", closing.anchor, record.fine_tune_seconds),
    ]
    files = [
        OutputFile("r6_chain_model", record.model),
        OutputFile("r6_chain_record", context.view.chain_record_file(closing.name).name),
    ]
    return detail, metrics, files


# ---------------------------------------------------------------- O1: one channel


def model_that_predicts(context: TickContext) -> ModelFile:
    """The R6 model that predicts the tick's week: the chain model of the week before it."""
    return chain_model_of(context, context.closing)


def channel_output_files(channel: str) -> list[OutputFile]:
    """The files of a channel's folder that the run manifest records (`eval` mode)."""
    files = [OutputFile(f"candidates/{channel}", CANDIDATES_FILE)]
    if channel == R1_CHANNEL:
        files.append(OutputFile("r1_bucket_scores", "r1_bucket_scores.parquet"))
    if channel in (R5_CHANNEL, R6_CHANNEL):
        files.append(OutputFile(f"vectors/{channel}", f"vectors/{METADATA_FILE}"))
    return files


def run_eval_channel(
    context: TickContext, setup: RecallSetup, queries: pl.DataFrame, channel: str
) -> StepOutcome:
    """One channel for the whole week, with the stage-1 functions of M6."""
    week = context.tick
    inputs = week_inputs(context, setup, week)
    if channel == R6_CHANNEL:
        start = model_that_predicts(context)
        chain = load_chain(context, setup, start)
        candidates, checked = predict_twotower_fold(
            chain,
            week.name,
            queries,
            inputs,
            context.view.candidates_file(week.name, channel),
            context.view.twotower_vectors_dir(week.name),
        )
        n_rows = candidates.height
        detail = f"{n_rows} rows from model {start.path.name} (sha256 {start.sha256})"
    else:
        job = FoldJob(
            paths=context.view,
            base=context.base,
            preprocess=context.preprocess,
            locked=setup.locked,
            fold=week.fold,
            fold_names=(week.name,),
            queries=queries,
            inputs=inputs,
        )
        result = generate_statistical_channel(job, channel)
        n_rows, checked = result.n_rows, result.checked_rows
        detail = f"{n_rows} rows"
    detail = f"{detail}; {checked} scores checked against the side files"
    metrics = [MetricRecord(f"candidates_rows/{channel}", week.anchor, float(n_rows))]
    return detail, metrics, channel_output_files(channel)


def run_serve_channel(
    context: TickContext, setup: RecallSetup, queries: pl.DataFrame, channel: str
) -> StepOutcome:
    """One channel for every customer: fitted once, written shard by shard."""
    week = context.tick
    job = RecallJob(
        paths=context.view,
        base=context.base,
        preprocess=context.preprocess,
        locked=setup.locked,
        week=week.fold,
        shard_customers=context.pipeline.shard_customers,
        queries=queries,
        inputs=week_inputs(context, setup, week),
    )
    result = generate_channel(
        job, channel, lambda: load_chain(context, setup, model_that_predicts(context))
    )
    detail = (
        f"{result.n_rows} rows in {result.n_shards} shards; {result.checked_rows} scores "
        "checked against the side files"
    )
    metrics = [MetricRecord(f"candidates_rows/{channel}", week.anchor, float(result.n_rows))]
    return detail, metrics, []


def run_recall(context: TickContext, step: Step) -> StepOutcome:
    """O1: generate one channel of the tick's week.

    Raises:
        ValueError: If the step names no known channel, the output breaks the
            schema, or a consistency check fails (scores against saved vectors).
    """
    if step.channel not in ALL_CHANNELS:
        raise ValueError(f"step {step.name} names no channel; expected one of {ALL_CHANNELS}")
    setup = load_recall_setup(context)
    queries = pl.read_parquet(context.view.queries_file(context.tick.name))
    if context.mode == EVAL_MODE:
        return run_eval_channel(context, setup, queries, step.channel)
    return run_serve_channel(context, setup, queries, step.channel)
